import { detectLandingLang, LANDING_LANGS, LANDING_LANG_LABELS, saveLandingLang, type LandingLang } from "./landing-i18n";

export type AuthLang = LandingLang | "pt" | "ar" | "zh-TW";
export const AUTH_LANGS = [...LANDING_LANGS, "zh-TW"] as const;
export const AUTH_LANG_LABELS: Record<AuthLang, string> = { ...LANDING_LANG_LABELS, "zh-TW": "繁體中文" };

export function detectAuthLang(): AuthLang {
  try {
    const saved = window.localStorage.getItem("traduchat:landing-lang");
    if (saved && (AUTH_LANGS as readonly string[]).includes(saved)) return saved as AuthLang;
  } catch { /* Storage may be unavailable. */ }
  const full = (navigator.language || "").toLowerCase();
  if (/^zh[-_](tw|hk|mo|hant)/.test(full)) return "zh-TW";
  const browserLang = full.split(/[-_]/)[0];
  if (browserLang === "pt" || browserLang === "ar") return browserLang;
  return detectLandingLang();
}

export function saveAuthLang(lang: AuthLang) {
  if (lang !== "pt" && lang !== "ar" && lang !== "zh-TW") {
    saveLandingLang(lang);
    return;
  }
  try {
    window.localStorage.setItem("traduchat:landing-lang", lang);
  } catch { /* Storage may be unavailable. */ }
}

